    private fun buildXrayConfig(uuid: String, tunFd: Int): JSONObject {
        val vmessUser = JSONObject()
            .put("id", uuid)
            .put("alterId", 0)
            .put("security", "auto")

        val vmessSettings = JSONObject().put("vnext", JSONArray().put(
            JSONObject()
                .put("address", SERVER_ADDRESS)
                .put("port", 443)
                .put("users", JSONArray().put(vmessUser))
        ))

        // TLS Directo configurado al dominio de tu DuckDNS
        val tlsSettings = JSONObject()
            .put("serverName", WS_HOST) // Usamos el dominio DuckDNS como SNI real
            .put("fingerprint", "chrome")
            .put("alpn", JSONArray().put("h2").put("http/1.1"))

        // Eliminamos el bloque de WebSockets ("ws") porque Xray escucha TLS directo en el puerto 443
        val streamSettings = JSONObject()
            .put("network", "tcp")
            .put("security", "tls")
            .put("tlsSettings", tlsSettings)

        val inbound = JSONObject()
            .put("tag", "tun-in")
            .put("port", 0)
            .put("protocol", "tun")
            .put("settings", JSONObject()
                .put("name", "fd://$tunFd") 
                .put("mtu", 1500)
                .put("autoRoute", false)
                .put("strictRoute", false)
                .put("stack", "gvisor") 
            )
            .put("sniffing", JSONObject()
                .put("enabled", true)
                .put("destOverride", JSONArray().put("http").put("tls").put("fakedns"))
                .put("routeOnly", true)
            )

        val outboundProxy = JSONObject()
            .put("tag", "proxy")
            .put("protocol", "vmess")
            .put("settings", vmessSettings)
            .put("streamSettings", streamSettings)

        val outboundDirect = JSONObject()
            .put("tag", "direct")
            .put("protocol", "freedom")

        val routing = JSONObject()
            .put("domainStrategy", "AsIs")
            .put("rules", JSONArray()
                .put(JSONObject()
                    .put("type", "field")
                    .put("port", "53")
                    .put("network", "udp,tcp")
                    .put("outboundTag", "proxy")
                )
                .put(JSONObject()
                    .put("type", "field")
                    .put("outboundTag", "proxy")
                    .put("network", "tcp,udp")
                )
            )

        val dns = JSONObject()
            .put("servers", JSONArray()
                .put("fakedns")
                .put("1.1.1.1")
                .put("8.8.8.8")
            )
            .put("queryStrategy", "UseIP")

        return JSONObject()
            .put("log", JSONObject().put("loglevel", "warning"))
            .put("dns", dns)
            .put("fakedns", JSONArray().put(JSONObject().put("ipPool", "198.18.0.0/15").put("poolSize", 65535)))
            .put("inbounds", JSONArray().put(inbound))
            .put("outbounds", JSONArray().put(outboundProxy).put(outboundDirect))
            .put("routing", routing)
    }
